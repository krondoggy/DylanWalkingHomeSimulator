import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const defaultMusicDirectory = fileURLToPath(new URL('../assets/music/', import.meta.url));
const supportedAudio = /\.(mp3|ogg|wav|m4a)$/i;

export async function buildMusicLibrary(musicDirectory = defaultMusicDirectory) {
  const files = (await readdir(musicDirectory, { withFileTypes: true }))
    .filter(entry => entry.isFile() && supportedAudio.test(entry.name))
    .map(entry => entry.name)
    .sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase(), 'en') || a.localeCompare(b, 'en'));

  const tracks = files.map(filename => ({
    title: filename.replace(supportedAudio, '').replace(/_+/g, ' ').trim() || filename,
    src: `assets/music/${encodeURIComponent(filename)}`
  }));

  const content = '// Generated by npm run music. Drop audio into assets/music, then run it again.\n'
    + `window.DWHS_MUSIC = ${JSON.stringify(tracks, null, 2)};\n`;
  await writeFile(path.join(musicDirectory, 'library.js'), content, 'utf8');
  return tracks;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const tracks = await buildMusicLibrary();
    console.log(`Music library updated: ${tracks.length} track${tracks.length === 1 ? '' : 's'}.`);
    if (!tracks.length) console.log('Drop audio files into assets/music, then run npm run music again.');
  } catch (error) {
    console.error(`Could not update the music library: ${error.message}`);
    process.exitCode = 1;
  }
}
